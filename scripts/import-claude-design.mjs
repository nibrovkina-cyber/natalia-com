#!/usr/bin/env node
/**
 * Import Claude Design zip → update globals.css tokens automatically.
 *
 * Usage:
 *   node scripts/import-claude-design.mjs ~/Downloads/nataliya.zip
 *   node scripts/import-claude-design.mjs ~/Downloads/nataliya.zip --dry
 *
 * Workflow:
 *  1. Unzip into docs/design-snapshots/<timestamp>/
 *  2. Parse design-system.html for CSS variables in :root and [data-palette="..."]
 *  3. Update app/globals.css palette blocks (warm + navy)
 *  4. Diff old vs new tokens — print summary
 *  5. Save snapshot for rollback
 */
import fs from "node:fs/promises";
import { existsSync } from "node:fs";
import path from "node:path";
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SNAPSHOT_DIR = path.join(ROOT, "docs", "design-snapshots");
const GLOBALS_PATH = path.join(ROOT, "app", "globals.css");

const args = process.argv.slice(2);
const zipPath = args.find((a) => !a.startsWith("--"));
const isDry = args.includes("--dry");

if (!zipPath) {
  console.error("Usage: node scripts/import-claude-design.mjs <zip-path> [--dry]");
  process.exit(1);
}

const stamp = new Date().toISOString().replace(/[:.]/g, "-").slice(0, 19);
const dest = path.join(SNAPSHOT_DIR, stamp);

async function run() {
  await fs.mkdir(dest, { recursive: true });

  console.log(`▸ unzip ${zipPath} → ${dest}`);
  await execCmd("unzip", ["-o", zipPath, "-d", dest]);

  const dsHtml = await findFile(dest, "design-system.html");
  if (!dsHtml) throw new Error("design-system.html not found in zip");

  const html = await fs.readFile(dsHtml, "utf-8");
  const palettes = extractPalettes(html);
  console.log(`▸ extracted palettes:`, Object.keys(palettes));

  const oldGlobals = await fs.readFile(GLOBALS_PATH, "utf-8");
  const newGlobals = updateGlobals(oldGlobals, palettes);

  const diff = diffTokens(oldGlobals, newGlobals);
  printDiff(diff);

  if (isDry) {
    console.log("\n--dry: not writing changes. New globals.css would be:");
    console.log(newGlobals.slice(0, 1000) + "\n…");
    return;
  }

  // backup current globals
  const backupPath = path.join(dest, "globals.css.before");
  await fs.writeFile(backupPath, oldGlobals);
  console.log(`▸ backup saved: ${backupPath}`);

  await fs.writeFile(GLOBALS_PATH, newGlobals);
  console.log(`✓ globals.css updated`);
  console.log(`\nNext: restart dev server, run npm run screenshot to verify.`);
}

function extractPalettes(html) {
  // Match :root, [data-palette="warm"] { ... } and [data-palette="navy"] { ... }
  const blocks = {};
  const blockRe = /(?:\:root,\s*\[data-palette="([^"]+)"\]|\[data-palette="([^"]+)"\])\s*\{([^}]+)\}/g;
  let m;
  while ((m = blockRe.exec(html))) {
    const name = m[1] || m[2];
    if (!name) continue;
    blocks[name] = parseVars(m[3]);
  }
  return blocks;
}

function parseVars(body) {
  const vars = {};
  body.split(";").forEach((line) => {
    const t = line.trim();
    if (!t.startsWith("--")) return;
    const idx = t.indexOf(":");
    if (idx < 0) return;
    const key = t.slice(0, idx).trim();
    const val = t
      .slice(idx + 1)
      .trim()
      .replace(/\/\*.*?\*\//g, "")
      .trim();
    vars[key] = val;
  });
  return vars;
}

function updateGlobals(css, palettes) {
  // Replace warm block
  if (palettes.warm) {
    css = css.replace(
      /(:root,\s*\[data-palette="warm"\]\s*\{)[\s\S]*?(\n\})/,
      `$1\n${formatVars(palettes.warm)}$2`
    );
  }
  // Replace navy block
  if (palettes.navy) {
    css = css.replace(
      /(\[data-palette="navy"\]\s*\{)[\s\S]*?(\n\})/,
      `$1\n${formatVars(palettes.navy)}$2`
    );
  }
  return css;
}

function formatVars(vars) {
  // preserve order from input + add legacy aliases inferred from existing names
  const lines = Object.entries(vars).map(([k, v]) => `  ${k}: ${v};`);
  // Add legacy aliases mapping if standard tokens present
  if (vars["--ink"] && !vars["--navy"]) {
    lines.push(
      `\n  /* Legacy aliases (auto-generated by import-claude-design.mjs) */`,
      `  --navy: var(--ink);`,
      `  --navy-2: var(--ink-2);`,
      `  --navy-3: var(--ink-3);`,
      `  --gold: var(--accent);`,
      `  --gold-2: var(--accent-soft);`,
      `  --gold-glow: var(--halo);`,
      `  --cream: var(--bg);`,
      `  --cream-2: var(--bg-card);`,
      `  --steel: var(--ink-3);`,
      `  --mint: ${vars["--good"] || "#5BBFA5"};`,
      `  --line: var(--hairline-2);`,
      `  --line-2: var(--hairline);`,
      `  --line-dark: rgba(255, 255, 255, 0.08);`,
      `  --line-dark-2: rgba(255, 255, 255, 0.14);`
    );
  }
  return lines.join("\n");
}

function diffTokens(oldCss, newCss) {
  const oldVars = parseAllVars(oldCss);
  const newVars = parseAllVars(newCss);
  const changed = [];
  const added = [];
  const removed = [];
  for (const k of new Set([...Object.keys(oldVars), ...Object.keys(newVars)])) {
    if (!(k in oldVars)) added.push([k, newVars[k]]);
    else if (!(k in newVars)) removed.push([k, oldVars[k]]);
    else if (oldVars[k] !== newVars[k]) changed.push([k, oldVars[k], newVars[k]]);
  }
  return { changed, added, removed };
}

function parseAllVars(css) {
  const out = {};
  // greedy: first :root or palette block
  const m = css.match(/:root,?\s*(?:\[data-palette[^\]]*\])?\s*\{([\s\S]*?)\n\}/);
  if (m) Object.assign(out, parseVars(m[1]));
  return out;
}

function printDiff({ changed, added, removed }) {
  if (changed.length) {
    console.log(`\n▸ tokens changed (${changed.length}):`);
    changed.forEach(([k, o, n]) => console.log(`    ${k}: ${o} → ${n}`));
  }
  if (added.length) {
    console.log(`\n▸ tokens added (${added.length}):`);
    added.forEach(([k, v]) => console.log(`    ${k}: ${v}`));
  }
  if (removed.length) {
    console.log(`\n▸ tokens removed (${removed.length}):`);
    removed.forEach(([k, v]) => console.log(`    ${k}: ${v}`));
  }
  if (!changed.length && !added.length && !removed.length) {
    console.log("\n▸ no token changes detected");
  }
}

async function findFile(dir, name) {
  const entries = await fs.readdir(dir, { withFileTypes: true });
  for (const e of entries) {
    if (e.isDirectory()) {
      const sub = await findFile(path.join(dir, e.name), name);
      if (sub) return sub;
    } else if (e.name === name) return path.join(dir, e.name);
  }
  return null;
}

function execCmd(cmd, args) {
  return new Promise((resolve, reject) => {
    const p = spawn(cmd, args, { stdio: "inherit" });
    p.on("exit", (code) => (code === 0 ? resolve() : reject(new Error(`${cmd} exited ${code}`))));
    p.on("error", reject);
  });
}

run().catch((e) => {
  console.error(`✗ ${e.message}`);
  process.exit(1);
});
